"""
최우선변제금(소액임차인 보호) 지역 등급 분류기
--------------------------------------------------
주택임대차보호법 시행령 제10조가 지역별로 다른 소액임차인 기준/최우선변제금액을 정하는데,
그 "지역"은 수도권정비계획법상 과밀억제권역 등의 개념을 그대로 가져다 쓴다. 이 모듈은
주소 문자열 하나를 받아 그 지역이 4단계(seoul/overcrowded/metropolitan/other) 중
어디에 해당하는지 판정한다.

⚠️ 정확도의 한계 — "억지로 채우지 않는다" 원칙을 여기도 그대로 적용한다:
과밀억제권역은 시/군 전역이 아니라 특정 "동" 단위로만 걸치는 예외가 실제로 있다
(예: 남양주시는 호평동·평내동 등 10개 동만 포함, 시흥시는 반월특수지역만 제외, 인천
서구는 대곡동 등 8개 동 + 경제자유구역 + 남동국가산업단지만 제외). 이 프로젝트는 주소를
"동" 단위까지 정밀하게 조회할 데이터 소스가 없으므로, 이런 시/군은 "unknown"(None)으로
정직하게 반환한다 — 잘못 분류해서 실제보다 더 안전하다고(또는 덜 안전하다고) 알려주는
것보다, "이 지역은 판정 못 한다"고 말하는 게 낫다.

출처 (2026-09-15 확인, 3개 독립 출처 교차 확인):
  - 국가법령정보센터 수도권정비계획법 시행령 제9조 별표1(과밀억제권역 범위)
  - 찾기쉬운 생활법령정보(easylaw.go.kr, 법제처) "소액보증금 우선변제" 페이지
  - 부동산케이스노트(realscasenote.com) 개정 연혁 정리
"""

PriorityRegion = str  # "seoul" | "overcrowded" | "metropolitan" | "other"

# 완전(전역) 포함 — 시/군/구 전체가 과밀억제권역인 곳만. 일부 동만 걸치는 곳은
# _AMBIGUOUS_PARTIAL_REGIONS에 따로 둔다.
_OVERCROWDED_FULL = [
    "인천광역시 중구", "인천 중구",
    "인천광역시 동구", "인천 동구",
    "인천광역시 미추홀구", "인천 미추홀구",
    "인천광역시 연수구", "인천 연수구",
    "인천광역시 남동구", "인천 남동구",
    "인천광역시 부평구", "인천 부평구",
    "인천광역시 계양구", "인천 계양구",
    "의정부시", "구리시", "하남시", "고양시", "수원시", "성남시",
    "안양시", "부천시", "광명시", "과천시", "의왕시", "군포시",
    "세종특별자치시", "세종시", "용인시", "화성시", "김포시",
]

# 광역시(과밀억제권역에 포함된 인천은 제외) + 명시된 경기 5개 시
_METROPOLITAN_FULL = [
    "부산광역시", "대구광역시", "광주광역시", "대전광역시", "울산광역시",
    "안산시", "광주시", "파주시", "이천시", "평택시",
]

# 시/군 전체가 아니라 "특정 동"만 과밀억제권역인 곳 — 주소만으로는 정밀 판정 불가
_AMBIGUOUS_PARTIAL_REGIONS = [
    "남양주시",  # 호평동/평내동/금곡동/일패동/이패동/삼패동/가운동/수석동/지금동/도농동만 포함
    "시흥시",    # 반월특수지역만 제외, 나머지는 포함
    "인천광역시 서구", "인천 서구",  # 대곡동 등 8개 동 + 경제자유구역 + 남동산단 제외
]

# 완전 제외(경기도 안이지만 과밀억제권역이 아닌 게 확실한 곳) — "그 밖의 지역"으로 확정
_CLEARLY_OTHER = [
    "인천광역시 강화군", "인천 강화군",
    "인천광역시 옹진군", "인천 옹진군",
]


def classify_priority_region(address_text: str) -> PriorityRegion | None:
    """
    주소 문자열(도로명 또는 지번 주소)을 받아 최우선변제금 지역 등급을 판정한다.

    Returns:
        "seoul" | "overcrowded" | "metropolitan" | "other" | None
        None은 "판정 불가"를 뜻한다 — 이 지역이 시/군 일부 동만 걸치는 예외 지역이라
        주소 문자열만으로는 정확히 알 수 없을 때 반환한다(추측해서 채우지 않는다).
    """
    if not address_text:
        return None

    text = address_text.strip()

    if "서울특별시" in text or text.startswith("서울"):
        return "seoul"

    for name in _AMBIGUOUS_PARTIAL_REGIONS:
        if name in text:
            return None

    for name in _CLEARLY_OTHER:
        if name in text:
            return "other"

    for name in _OVERCROWDED_FULL:
        if name in text:
            return "overcrowded"

    for name in _METROPOLITAN_FULL:
        if name in text:
            return "metropolitan"

    # 위 목록에 없는 나머지 전부(강원/충청/전라/경북/경남/제주, 그리고 나열되지 않은
    # 경기도 시/군)는 4호 "그 밖의 지역" — 이건 확정적으로 분류 가능하다(과밀억제권역·
    # 광역시 목록이 전부 명시적 열거이므로, 거기 없으면 자동으로 4호가 맞다).
    return "other"
